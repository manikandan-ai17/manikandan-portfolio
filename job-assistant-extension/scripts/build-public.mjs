// Builds the public download: the extension without anyone's personal details, as a ZIP the site serves.
//   npm run build:public      →  ../public/downloads/job-assistant-extension.zip
// The portfolio edition (the folder you load while developing) keeps reading the owner's profile from the
// portfolio; this edition starts blank and the visitor types their own details on the Profile page.

import { deflateRawSync, crc32 } from 'node:zlib'
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ext = join(here, '..', 'extension')
const out = join(here, '..', '..', 'public', 'downloads', 'job-assistant-extension.zip')
const ROOT = 'job-assistant-extension' // the folder the ZIP unpacks to

const BLANK_SEED = {
  source: 'blank',
  fullName: '', firstName: '', lastName: '', headline: '', summary: '', email: '', country: '',
  links: { portfolio: '', github: '', linkedin: '' },
  resumeUrl: '',
  education: [], experience: [], projects: [], skillGroups: [], openSource: [],
}

const INSTALL = `Job Application Assistant — install in Chrome (2 minutes)

1. Unzip this file. You get a folder named "job-assistant-extension".
2. In Chrome open  chrome://extensions  and switch on "Developer mode" (top right).
3. Click "Load unpacked" and choose the unzipped "job-assistant-extension" folder.
4. Click the puzzle-piece icon, pin "Job Application Assistant", and open it.
5. Open "Profile" and fill in "Your details", "Answers only you can give" and add your resume (PDF).
6. Optional: paste your own Gemini or Claude API key under "AI drafts". It is stored only in this browser.

Everything stays in this browser. Nothing is sent anywhere except the company job boards and the AI provider
you choose. Auto-apply is OFF by default; turn it on in Profile, and keep "Dry run" ticked until you have
checked a few filled forms. It never runs on LinkedIn, Indeed or Wellfound. It does not solve CAPTCHAs, and it
stops and asks you whenever an answer is not in your profile.
`

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

const files = walk(ext).map((p) => ({ name: `${ROOT}/${relative(ext, p).split(sep).join('/')}`, data: readFileSync(p) }))
const put = (name, data) => {
  const i = files.findIndex((f) => f.name === name)
  const entry = { name, data: Buffer.from(data) }
  if (i < 0) files.push(entry)
  else files[i] = entry
}
put(`${ROOT}/src/lib/seedProfile.js`, `// Blank starting profile: you type your own details on the Profile page. Generated by scripts/build-public.mjs.\nexport const SEED_PROFILE = ${JSON.stringify(BLANK_SEED, null, 2)}\n`)
const manifest = JSON.parse(readFileSync(join(ext, 'manifest.json'), 'utf8'))
manifest.host_permissions = manifest.host_permissions.filter((h) => !/manikandan-portfolio/.test(h)) // that one reads the owner's resume
put(`${ROOT}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n')
put(`${ROOT}/INSTALL.txt`, INSTALL)

// A minimal ZIP writer (deflate), so the build needs no extra packages.
const dosTime = (d) => ((d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1)) & 0xffff
const dosDate = (d) => (((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate()) & 0xffff
const now = new Date()
const chunks = []
const central = []
let offset = 0
for (const f of files.sort((a, b) => a.name.localeCompare(b.name))) {
  const name = Buffer.from(f.name)
  const comp = deflateRawSync(f.data, { level: 9 })
  const crc = crc32(f.data) >>> 0
  const local = Buffer.alloc(30)
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8)
  local.writeUInt16LE(dosTime(now), 10); local.writeUInt16LE(dosDate(now), 12); local.writeUInt32LE(crc, 14)
  local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(f.data.length, 22); local.writeUInt16LE(name.length, 26)
  chunks.push(local, name, comp)
  const c = Buffer.alloc(46)
  c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(20, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(0x0800, 8); c.writeUInt16LE(8, 10)
  c.writeUInt16LE(dosTime(now), 12); c.writeUInt16LE(dosDate(now), 14); c.writeUInt32LE(crc, 16)
  c.writeUInt32LE(comp.length, 20); c.writeUInt32LE(f.data.length, 24); c.writeUInt16LE(name.length, 28); c.writeUInt32LE(offset, 42)
  central.push(c, name)
  offset += local.length + name.length + comp.length
}
const centralBuf = Buffer.concat(central)
const end = Buffer.alloc(22)
end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10)
end.writeUInt32LE(centralBuf.length, 12); end.writeUInt32LE(offset, 16)

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, Buffer.concat([...chunks, centralBuf, end]))
console.log(`${out}\n${files.length} files, ${(statSync(out).size / 1024).toFixed(0)} KB`)
