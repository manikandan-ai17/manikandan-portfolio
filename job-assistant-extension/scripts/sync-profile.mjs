// Regenerates src/lib/seedProfile.js from the portfolio's own data file (../src/data/portfolio.ts), so the
// assistant starts from exactly the facts published on the site. Run after editing the portfolio:
//   npm run sync-profile
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(join(here, '..', '..', 'src', 'data', 'portfolio.ts'), 'utf8')
const body = src.replace(/^\s*export\s+const\s+portfolioData\s*=\s*/m, 'return ')
// The file is a plain object literal (no types), written by its owner: evaluate it as such.
const p = new Function(body)()

const jobs = p.experiences.filter((e) => !e.id)
const projects = p.experiences.filter((e) => e.id).map((e) => {
  const big = p.bigProjects.find((b) => b.id === e.id)
  return { id: e.id, name: e.role, where: e.company, summary: e.desc, bullets: e.descBullets, tech: e.tech, status: big?.status ?? e.company, github: big?.github ?? null }
})
const [first, ...rest] = p.name.split(' ')
const edu = p.education.map((e) => {
  const [start, end] = String(e.duration).split(/\s*[—–-]\s*/)
  return { school: e.school, degree: e.degree, start: start?.trim() ?? null, end: end?.trim() ?? null, gpa: (/CGPA\s*(\d+(?:\.\d+)?)/.exec(e.desc) ?? [])[1] ?? null, notes: e.descBullets }
})

const seed = {
  source: 'portfolio',
  syncedFrom: 'src/data/portfolio.ts',
  fullName: p.name,
  firstName: first,
  lastName: rest.join(' '),
  headline: p.roleLabel,
  summary: p.subTitle,
  email: p.contactEmail,
  country: p.location,
  links: { portfolio: 'https://manikandan-portfolio-delta.vercel.app/', github: p.githubLink, linkedin: p.linkedinLink },
  resumeUrl: 'https://manikandan-portfolio-delta.vercel.app/Manikandan_Santhosh_Resume.pdf',
  education: edu,
  experience: jobs.map((e) => ({ title: e.role, company: e.company, dates: e.date, summary: e.desc, bullets: e.descBullets, tech: e.tech })),
  projects,
  skillGroups: p.techSkills.map((g) => ({ domain: g.domain, items: g.items })),
  openSource: p.openSource.map((o) => ({ name: o.name, url: o.url, lang: o.lang, desc: o.desc })),
}

const out = `// GENERATED by scripts/sync-profile.mjs from ../src/data/portfolio.ts — do not edit by hand.\nexport const SEED_PROFILE = ${JSON.stringify(seed, null, 2)}\n`
writeFileSync(join(here, '..', 'extension', 'src', 'lib', 'seedProfile.js'), out)
console.log(`seedProfile.js written: ${jobs.length} roles, ${projects.length} projects, ${edu.length} education entries`)
